/**
 * Route continuity + altitude test (run: npm run test:continuity).
 * Writes qa/continuity_report.json and docs/path_graph.md (altitude chart), exits 1 on failure.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { Course, validateContinuity, WORLD } from '../src/world/course';

const c = new Course();
const r = validateContinuity(c);
mkdirSync('qa', { recursive: true });
mkdirSync('docs', { recursive: true });
writeFileSync('qa/continuity_report.json', JSON.stringify({ length: c.length, marks: c.marks, ...r }, null, 2));

// altitude chart (ASCII) + per-stage table
const rows: string[] = [];
rows.push('# Rainbow route graph — absolute altitudes & continuity');
rows.push('');
rows.push(`Generated by \`npm run test:continuity\`. Route length **${c.length.toFixed(1)} units** (1 unit ≈ 5 cm at Benny scale).`);
rows.push('One centripetal Catmull-Rom spline from scene 01 to the towel at the end of 10; scene 11 is the');
rows.push('victory cinematic at the route end. Result: **' + (r.ok ? 'PASS' : 'FAIL') + '**.');
rows.push('');
rows.push('| Stage | Title | s0 → s1 | length | altitude in → out | width | tube | speed |');
rows.push('|---|---|---|---|---|---|---|---|');
for (const st of c.stages) {
  const y0 = c.sample(st.s0).pos.y, y1 = c.sample(st.s1).pos.y;
  rows.push(`| ${st.id} | ${st.title} | ${st.s0.toFixed(1)} → ${st.s1.toFixed(1)} | ${(st.s1 - st.s0).toFixed(1)} | ${y0.toFixed(1)} → ${y1.toFixed(1)} | ${st.width} | ${st.tube ? st.tubeKind + ' r=' + st.tube : 'open'} | ${st.speed} |`);
}
rows.push('');
rows.push('## Boundary continuity (sampled ±0.02 units across each boundary)');
rows.push('');
rows.push('| From → To | s | position gap | tangent Δ° | up Δ° | altitude |');
rows.push('|---|---|---|---|---|---|');
for (const b of r.boundaries) rows.push(`| ${b.from} → ${b.to} | ${b.s} | ${b.posGap} | ${b.tangentAngleDeg} | ${b.upAngleDeg} | ${b.altitude} |`);
rows.push('');
rows.push(`Max tangent change per 0.25-unit step: **${r.maxStepTangentDeg}°**; max position step: **${r.maxStepPos}** (no jumps).`);
rows.push('');
rows.push('## 07 → 08 deep plunge');
rows.push('');
const p = r.plunge;
rows.push(`* 07 entry altitude: **${p.entryAltitude07}**`);
rows.push(`* plunge top (end of visible winding stretch): s=${p.plungeTop.s}, y=**${p.plungeTop.y}**`);
rows.push(`* plunge middle: s=${p.plungeMid.s}, y=**${p.plungeMid.y}**`);
rows.push(`* plunge bottom (pull-up complete): s=${p.plungeBottom.s}, y=**${p.plungeBottom.y}**`);
rows.push(`* 08 inlet (chamber back wall z=${WORLD.chamber.zBack}): s=${p.inlet08.s}, y=**${p.inlet08.y}**`);
rows.push(`* total vertical drop top→inlet: **${p.verticalDrop} units (≈${(p.verticalDrop * 0.05).toFixed(2)} m at Benny scale)**, steepest pitch ${p.minPitchDeg}°`);
rows.push('');
rows.push('## Altitude profile (y vs s)');
rows.push('');
rows.push('```');
const W = 72, H = 22;
let ymin = Infinity, ymax = -Infinity;
for (let s = 0; s <= c.length; s += 1) { const y = c.sample(s).pos.y; ymin = Math.min(ymin, y); ymax = Math.max(ymax, y); }
const grid = Array.from({ length: H }, () => Array(W).fill(' '));
for (let x = 0; x < W; x++) {
  const s = (x / (W - 1)) * c.length;
  const y = c.sample(s).pos.y;
  const row = Math.round(((ymax - y) / (ymax - ymin)) * (H - 1));
  grid[row][x] = '█';
}
for (const st of c.stages) {
  const x = Math.round((st.s0 / c.length) * (W - 1));
  grid[H - 1][x] = st.id[1];
}
grid.forEach((row, i) => rows.push(`${(ymax - (i / (H - 1)) * (ymax - ymin)).toFixed(0).padStart(5)} |${row.join('')}`));
rows.push('       stage start digits on the bottom row (1=01 … 0=10, 1=11)');
rows.push('```');
writeFileSync('docs/path_graph.md', rows.join('\n') + '\n');

console.log(JSON.stringify({ ok: r.ok, length: +c.length.toFixed(1), plunge: r.plunge, maxStepTangentDeg: r.maxStepTangentDeg, boundaries: r.boundaries.map((b) => `${b.from}->${b.to} gap=${b.posGap} dT=${b.tangentAngleDeg} y=${b.altitude}`) }, null, 1));
process.exit(r.ok ? 0 : 1);
