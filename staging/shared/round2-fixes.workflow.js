function prior(list) {
  const done = list.filter(Boolean)
  if (!done.length) return ''
  return '\nWHAT EARLIER AGENTS OF THIS ROUND CHANGED (verify in the files; their final stills show the current state):\n' +
    done.map(r => `- ${r.area} (${r.status}): files ${JSON.stringify(r.files_changed)}; final still ${r.final_still}; ` +
      `shared changes: ${r.shared_changes || 'none'}; notes: ${r.notes_for_next_agents}`).join('\n')
}

function implPrompt(key, extra) {
  return COMMON + '\n' + AREAS[key] + (extra || '')
}

function fix(key, extra) {
  if (SKIP.includes(key)) {
    log('skipping ' + key + ' (finished in an earlier run)')
    return Promise.resolve({
      area: key, status: 'finished in an earlier run', files_changed: [], changes: [], final_cycle_exit: 0,
      final_still: '', final_sbs: '', improved: [], still_different: [], shared_changes: 'see notes',
      notes_for_next_agents: 'Finished in an earlier run: read C:\\RainbowUnity\\evidence\\screen05\\round2_progress\\NOTES.md for what it changed and what still differs.',
    })
  }
  return agent(implPrompt(key, extra), { label: 'fix:' + key, phase: 'Fix', schema: IMPL_SCHEMA })
}

